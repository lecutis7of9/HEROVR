#!/usr/bin/env python3
"""Writes server/vps/cloud-init.sh: one script that turns a fresh Ubuntu 24.04 droplet into the HERO VR server
(Node, Caddy for HTTPS on IP.sslip.io, the firewall, a systemd service). The server files are inlined, so the
droplet needs nothing from GitHub. Run after changing any server file:  python3 server/vps/make-cloud-init.py
SM2 VR (port of SpidyVR to Marvel's Spider-Man 2), GPLv3. Made by Agent Mulder."""
import os
here = os.path.dirname(os.path.abspath(__file__))
files = {'lobby/src/lobby.mjs': '../lobby/src/lobby.mjs', 'relay/relay-core.mjs': '../relay/relay-core.mjs',
         'vps/herovr-server.mjs': 'herovr-server.mjs'}
out = ['#!/bin/bash',
       '# HERO VR server setup for a fresh Ubuntu 24.04 droplet (paste as the droplet\'s initialization script, or run',
       '# as root: bash cloud-init.sh). Made by Agent Mulder. GENERATED by make-cloud-init.py - do not edit by hand.',
       'set -euo pipefail', 'export DEBIAN_FRONTEND=noninteractive',
       'apt-get update -y', 'apt-get install -y nodejs caddy ufw curl openssl',
       'mkdir -p /opt/herovr/lobby/src /opt/herovr/relay /opt/herovr/vps']
for dest, src in files.items():
    text = open(os.path.join(here, src)).read()
    assert 'HEROVR_EOF' not in text
    out += [f"cat > /opt/herovr/{dest} <<'HEROVR_EOF'", text.rstrip('\n'), 'HEROVR_EOF']
out += [
    '# The public address: DigitalOcean\'s metadata, else ask the internet.',
    'IP=$(curl -fs --max-time 5 http://169.254.169.254/metadata/v1/interfaces/public/0/ipv4/address || curl -fs --max-time 10 https://api.ipify.org)',
    'NAME=$(echo "$IP" | tr . -).sslip.io',
    'if [ ! -f /etc/herovr.env ]; then',
    '  umask 077',
    '  printf "RELAY_SECRET=%s\\nRELAY_ADDR=%s:3479\\n" "$(openssl rand -hex 24)" "$IP" > /etc/herovr.env',
    'fi',
    'id herovr >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin herovr',
    'chown root:herovr /etc/herovr.env && chmod 640 /etc/herovr.env',
    "cat > /etc/systemd/system/herovr.service <<'HEROVR_EOF'",
    '[Unit]', 'Description=HERO VR server list + relay', 'After=network-online.target', 'Wants=network-online.target', '',
    '[Service]', 'User=herovr', 'EnvironmentFile=/etc/herovr.env', 'ExecStart=/usr/bin/node /opt/herovr/vps/herovr-server.mjs',
    'Restart=always', 'RestartSec=2', 'NoNewPrivileges=true', 'ProtectSystem=strict', 'ProtectHome=true', 'PrivateTmp=true', '',
    '[Install]', 'WantedBy=multi-user.target', 'HEROVR_EOF',
    'printf "%s {\\n\\treverse_proxy 127.0.0.1:8080\\n}\\n" "$NAME" > /etc/caddy/Caddyfile',
    'ufw allow 22/tcp && ufw allow 80/tcp && ufw allow 443/tcp && ufw allow 3479/udp && ufw --force enable',
    'systemctl daemon-reload && systemctl enable --now herovr && systemctl restart caddy',
    'echo "HERO VR server: https://$NAME  (check: https://$NAME/v1/health)" | tee /root/HEROVR-URL.txt',
]
open(os.path.join(here, 'cloud-init.sh'), 'w').write('\n'.join(out) + '\n')
print('wrote cloud-init.sh')
