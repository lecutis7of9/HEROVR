// Builds include/spidy/gesture_everyday.hpp: the everyday motions found in the replay logs
// (tests/replay/*.csv), grouped so the gesture recorder can warn when a custom move looks like
// normal play.  Run from the repo root:
//   g++ -std=c++20 -O2 -Iinclude tools/gesture_everyday_gen.cpp -o /tmp/gen && /tmp/gen
#include "spidy/gesture_remap.hpp"
#include <cstring>
#include <cstdio>
#include <algorithm>
#include <vector>
#include <fstream>
#include <sstream>
#include <string>
using namespace spidy; using namespace spidy::gesture_remap;
struct Row{double t; Pose head, hand[2]; bool ok[3]; uint32_t presses;};
std::vector<Row> loadRun(const std::string& name){ std::vector<Row> rows; std::ifstream in("tests/replay/"+name+".csv"); std::string line;
 while(std::getline(in,line)){ if(line.empty()||line[0]=='#') continue; std::vector<double> v; std::stringstream ss(line); std::string c; while(std::getline(ss,c,',')) v.push_back(c=="nan"?NAN:strtod(c.c_str(),0)); if(v.size()<32) continue;
 Row r; r.t=v[0]; auto pose=[&](size_t i){return Pose{{float(v[i]),float(v[i+1]),float(v[i+2])},{float(v[i+3]),float(v[i+4]),float(v[i+5]),float(v[i+6])}};};
 r.head=pose(1); r.hand[0]=pose(8); r.hand[1]=pose(15); r.ok[0]=finite(r.head.position)&&length(r.head.position)>1e-6f; for(int h=0;h<2;++h) r.ok[1+h]=finite(r.hand[h].position)&&length(r.hand[h].position)>1e-6f; r.presses=uint32_t(v[23]); rows.push_back(r);} return rows;}

int main() {
    const char* runs[] = {"run384", "run382", "run381", "run38", "run372", "run371", "run36"};
    std::vector<Shape> all;
    Shape none[slots]{};
    for (auto run : runs) {
        auto rows = loadRun(run);
        if (rows.size() < 2) continue;
        Capture cap;
        std::vector<double> pr;
        for (size_t i = 1; i < rows.size(); ++i)
            if (rows[i].presses > rows[i - 1].presses) pr.push_back(rows[i].t - .03);
        size_t i = 0;
        const double step = 1 / 90.;
        for (double t = rows.front().t; t <= rows.back().t; t += step) {
            while (i + 1 < rows.size() && rows[i + 1].t <= t) ++i;
            const Row& a = rows[i];
            const Row& b = i + 1 < rows.size() ? rows[i + 1] : rows[i];
            const double gap = b.t - a.t;
            const float s = gap > 1e-6 ? float(std::clamp((t - a.t) / gap, 0., 1.)) : 0;
            const bool joined = gap < .15;
            Capture::Frame f;
            f.seconds = float(step);
            f.head = a.head.position + (b.head.position - a.head.position) * s;
            f.look = a.head.orientation.rotate(Vec3{0, 0, -1});
            if (!(a.ok[0] && joined)) f.head = {NAN, 0, 0};
            for (int h = 0; h < 2; ++h) {
                f.tracked[h] = a.ok[1 + h] && b.ok[1 + h] && joined;
                f.hand[h] = a.hand[h].position + (b.hand[h].position - a.hand[h].position) * s;
            }
            auto it = std::upper_bound(pr.begin(), pr.end(), t);
            f.buttons[1] = (it != pr.begin() && t - *(it - 1) < .25) ? trigger : 0;
            if (cap.push(f, .6f)) all.push_back(cap.shape());
        }
    }
    const size_t n = all.size();
    std::vector<float> d(n * n, 1e9f);
    for (size_t i = 0; i < n; ++i)
        for (size_t j = i; j < n; ++j)
            if (all[i].hands == all[j].hands)
                d[i * n + j] = d[j * n + i] = i == j ? 0 : distance(all[i], all[j], all[i].hands);
    const float radius = .30f;
    std::vector<char> covered(n);
    std::vector<size_t> picks;
    while (picks.size() < 96) {
        size_t best = n;
        int bestCount = 0;
        for (size_t i = 0; i < n; ++i) {
            if (covered[i]) continue;
            int c = 0;
            for (size_t j = 0; j < n; ++j) c += !covered[j] && d[i * n + j] < radius;
            if (c > bestCount) bestCount = c, best = i;
        }
        if (best == n || bestCount < 3) break;
        picks.push_back(best);
        for (size_t j = 0; j < n; ++j)
            if (d[best * n + j] < radius) covered[j] = 1;
    }
    FILE* o = std::fopen("include/spidy/gesture_everyday.hpp", "w");
    if (!o) return 1;
    std::fprintf(o, "// Generated by tools/gesture_everyday_gen.cpp from %zu motions in the replay logs. Do not edit.\n", n);
    std::fprintf(o, "#pragma once\n#include <cstdint>\n#include \"spidy/gesture_remap.hpp\"\n\nnamespace spidy::gesture_everyday {\n\n");
    std::fprintf(o, "struct Packed {\n    uint8_t hands;\n    uint8_t buttons[2];\n    uint8_t tenths;\n    int16_t v[2][gesture_remap::points][3];\n};\n\n");
    std::fprintf(o, "inline constexpr int count = %zu;\n\ninline constexpr Packed packed[count] = {\n", picks.size());
    for (size_t p : picks) {
        const Shape& s = all[p];
        std::fprintf(o, "    {%u, {%u, %u}, %d, {", s.hands, s.buttons[0], s.buttons[1], int(std::lround(std::min(s.seconds, 25.f) * 10)));
        for (int h = 0; h < 2; ++h) {
            std::fprintf(o, "{");
            for (int k = 0; k < points; ++k) {
                const Vec3 v = (s.hands & (1u << h)) ? s.path[h][k] : Vec3{};
                std::fprintf(o, "{%d,%d,%d},", int(std::lround(std::clamp(v.x, -30.f, 30.f) * 1000)),
                             int(std::lround(std::clamp(v.y, -30.f, 30.f) * 1000)), int(std::lround(std::clamp(v.z, -30.f, 30.f) * 1000)));
            }
            std::fprintf(o, "}%s", h == 0 ? "," : "");
        }
        std::fprintf(o, "}},\n");
    }
    std::fprintf(o, "};\n\n");
    std::fprintf(o, "%s", R"GEN(// Unpacked once into static storage (no heap); names say which hands move.
struct Table {
    gesture_remap::Shape shapes[count];
    const char* names[count];
};

inline const Table& table() {
    static const Table t = [] {
        Table r{};
        for (int i = 0; i < count; ++i) {
            const Packed& p = packed[i];
            gesture_remap::Shape& s = r.shapes[i];
            s.valid = true;
            s.hands = p.hands;
            s.buttons[0] = p.buttons[0];
            s.buttons[1] = p.buttons[1];
            s.anyButtons = true;
            s.seconds = float(p.tenths) / 10;
            s.tolerance = gesture_remap::minTolerance;
            for (int h = 0; h < 2; ++h)
                for (int k = 0; k < gesture_remap::points; ++k)
                    s.path[h][k] = {float(p.v[h][k][0]) / 1000, float(p.v[h][k][1]) / 1000, float(p.v[h][k][2]) / 1000};
            r.names[i] = p.hands == 3 ? "NORMAL PLAY MOTION (BOTH HANDS)"
                       : p.hands == 1 ? "NORMAL PLAY MOTION (LEFT HAND)"
                                      : "NORMAL PLAY MOTION (RIGHT HAND)";
        }
        return r;
    }();
    return t;
}

}  // namespace spidy::gesture_everyday
)GEN");
    std::fclose(o);
    std::printf("motions %zu groups %zu\n", n, picks.size());
}
